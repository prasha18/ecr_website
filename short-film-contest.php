<script>
        function validateMobileNumber() {
            const mobileInput = document.getElementById('phone');
            const mobileNumber = mobileInput.value;
            const errorMessage = document.getElementById('error-message');

            if (mobileNumber.length < 10) {
                errorMessage.textContent = 'Mobile number must be at least 10 digits long.';
                mobileInput.setCustomValidity('Invalid field.');
            } else {
                errorMessage.textContent = '';
                mobileInput.setCustomValidity('');
            }
        }

        window.addEventListener('DOMContentLoaded', () => {
            const mobileInput = document.getElementById('phone');
            mobileInput.addEventListener('input', validateMobileNumber);
        });
    </script>
